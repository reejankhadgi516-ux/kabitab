foreach ( $works as $seed => $work ) {
	$stories = get_posts(
		array(
			'post_type'      => 'kabitab_story',
			'post_status'    => 'any',
			'posts_per_page' => 1,
			'meta_key'       => '_kabitab_genre_starter_seed',
			'meta_value'     => $seed,
			'no_found_rows'  => true,
		)
	);
	if ( empty( $stories ) ) {
		fwrite( STDERR, sprintf( "Starter story not found for %s.\n", $seed ) );
		continue;
	}

	$story    = $stories[0];
	$chapters = get_posts(
		array(
			'post_type'      => 'kabitab_chapter',
			'post_status'    => 'any',
			'posts_per_page' => -1,
			'meta_key'       => '_kabitab_parent_story',
			'meta_value'     => $story->ID,
			'orderby'        => 'meta_value_num',
			'order'          => 'ASC',
			'no_found_rows'  => true,
		)
	);
	if ( empty( $chapters ) ) {
		fwrite( STDERR, sprintf( "No chapter found for %s.\n", $story->post_title ) );
		continue;
	}

	wp_update_post(
		array(
			'ID'           => $chapters[0]->ID,
			'post_title'   => $work['chapter'],
			'post_content' => $work['content'],
			'post_status'  => 'publish',
		)
	);
	update_post_meta( $story->ID, '_kabitab_status', $work['status'] );

	if ( ! empty( $work['extra_chapters'] ) ) {
		foreach ( $work['extra_chapters'] as $number => $extra ) {
			$matches = get_posts(
				array(
					'post_type'      => 'kabitab_chapter',
					'post_status'    => 'any',
					'posts_per_page' => 1,
					'meta_query'     => array(
						array( 'key' => '_kabitab_parent_story', 'value' => $story->ID ),
						array( 'key' => '_kabitab_chapter_number', 'value' => $number ),
					),
					'no_found_rows'  => true,
				)
			);
			if ( empty( $matches ) ) {
				wp_insert_post(
					array(
						'post_type'    => 'kabitab_chapter',
						'post_status'  => 'publish',
						'post_title'   => $extra['title'],
						'post_content' => $extra['content'],
						'post_author'  => $story->post_author,
						'meta_input'   => array(
							'_kabitab_parent_story'    => $story->ID,
							'_kabitab_chapter_number' => $number,
						),
					)
				);
			} else {
				wp_update_post(
					array(
						'ID'           => $matches[0]->ID,
						'post_title'   => $extra['title'],
						'post_content' => $extra['content'],
						'post_status'  => 'publish',
					)
				);
			}
		}
	}

	fwrite( STDOUT, sprintf( "Expanded: %s\n", $story->post_title ) );
}

fwrite( STDOUT, "Expanded all genre starter entries.\n" );
