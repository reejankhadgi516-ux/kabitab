$created = 0;
foreach ( $stories as $seed ) {
	$existing = get_posts(
		array(
			'post_type'      => 'kabitab_story',
			'post_status'    => 'any',
			'posts_per_page' => 1,
			'fields'         => 'ids',
			'meta_key'       => '_kabitab_genre_starter_seed',
			'meta_value'     => $seed['slug'],
			'no_found_rows'  => true,
		)
	);
	if ( ! empty( $existing ) ) {
		continue;
	}

	$term = term_exists( $seed['slug'], 'story_genre' );
	if ( ! $term ) {
		$term = wp_insert_term( $seed['genre'], 'story_genre', array( 'slug' => $seed['slug'] ) );
	}
	if ( is_wp_error( $term ) ) {
		fwrite( STDERR, sprintf( "Could not create genre for %s.\n", $seed['title'] ) );
		continue;
	}
	$term_id = is_array( $term ) ? (int) $term['term_id'] : (int) $term;

	$story_id = wp_insert_post(
		array(
			'post_type'    => 'kabitab_story',
			'post_status'  => 'draft',
			'post_title'   => $seed['title'],
			'post_excerpt' => $seed['blurb'],
			'post_author'  => $author_id,
			'meta_input'   => array(
				'_kabitab_blurb'            => $seed['blurb'],
				'_kabitab_status'           => 'ongoing',
				'_kabitab_genre_starter_seed' => $seed['slug'],
			),
		),
		true
	);
	if ( is_wp_error( $story_id ) ) {
		fwrite( STDERR, sprintf( "Could not create %s.\n", $seed['title'] ) );
		continue;
	}

	wp_set_object_terms( $story_id, array( $term_id ), 'story_genre', false );
	$chapter_id = wp_insert_post(
		array(
			'post_type'   => 'kabitab_chapter',
			'post_status' => 'draft',
			'post_title'  => $seed['chapter'],
			'post_content' => $seed['content'],
			'post_author' => $author_id,
			'meta_input'  => array(
				'_kabitab_parent_story'    => $story_id,
				'_kabitab_chapter_number' => 1,
			),
		),
		true
	);
	if ( is_wp_error( $chapter_id ) ) {
		wp_delete_post( $story_id, true );
		fwrite( STDERR, sprintf( "Could not create chapter for %s.\n", $seed['title'] ) );
		continue;
	}

	++$created;
	fwrite( STDOUT, sprintf( "Created draft: %s\n", $seed['title'] ) );
}

fwrite( STDOUT, sprintf( "Created %d genre starter drafts.\n", $created ) );
